/// 단위 명사 앞에 쓰는 고유어 수(한 쪽, 두 쪽, 열두 쪽, 스무 쪽, 스물네 쪽).
/// 99를 넘으면 숫자로 쓴다.
String koreanCount(int n) {
  if (n <= 0 || n > 99) return '$n';
  const ones = ['', '한', '두', '세', '네', '다섯', '여섯', '일곱', '여덟', '아홉'];
  const tens = ['', '열', '스물', '서른', '마흔', '쉰', '예순', '일흔', '여든', '아흔'];
  final t = n ~/ 10, o = n % 10;
  if (t == 2 && o == 0) return '스무';
  return '${tens[t]}${ones[o]}';
}
