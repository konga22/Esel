/// 시연(mock) 모드의 예시 인물 한 명.
///
/// 하네스 `demoPeople`과 디자인 생성기 `lib.mjs`의 `PEOPLE`을 옮겼다. 사진 비율(세로/가로)과
/// 얼굴 위치·폭(사진에 대한 비율)은 생성기가 macOS Vision으로 잰 값이다. 이름·캡션·시각은
/// 지어낸 예시이고 실제 사람이나 통계가 아니다. 사진 출처는 `assets/README.md`.
class DemoPerson {
  final String name;
  final String photoAsset;
  final double ratio;
  final double faceX;
  final double faceY;
  final double faceWidth;
  final EselPaint color;

  /// 올리기 시각 표기(`오전 8:12`). 안쪽 지면 머리에 그대로 쓴다.
  final String time;
  final String caption;

  /// 사진의 대체 텍스트(착장 설명).
  final String alt;

  const DemoPerson(
    this.name,
    this.photoAsset, {
    required this.ratio,
    required this.faceX,
    required this.faceY,
    required this.faceWidth,
    required this.color,
    required this.time,
    required this.caption,
    required this.alt,
  });

  /// `time`을 그날 0시부터의 분으로. 같은 색 방의 최신순 정렬에 쓴다.
  int get minuteOfDay {
    final match = RegExp(r'(오전|오후) (\d{1,2}):(\d{2})').firstMatch(time)!;
    var hour = int.parse(match[2]!) % 12;
    if (match[1] == '오후') hour += 12;
    return hour * 60 + int.parse(match[3]!);
  }
}

