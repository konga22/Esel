// Tool to generate Dart design tokens from harness.json
// Run with: dart run tool/generate_tokens.dart (inside flutter_app directory)

import 'dart:convert';
import 'dart:io';

const Map<String, Map<String, String>> paintMeta = {
  'sage': {'nameKo': '세이지', 'nameEn': 'Sage', 'hex': '#A8B5A0'},
  'butter': {'nameKo': '버터', 'nameEn': 'Butter', 'hex': '#E3C878'},
  'powder': {'nameKo': '파우더 블루', 'nameEn': 'Powder blue', 'hex': '#A9BDDC'},
  'coral': {'nameKo': '코랄', 'nameEn': 'Coral', 'hex': '#EE8C76'},
  'lilac': {'nameKo': '라일락', 'nameEn': 'Lilac', 'hex': '#BBA6D6'},
  'terracotta': {'nameKo': '테라코타', 'nameEn': 'Terracotta', 'hex': '#C2643F'},
  'burgundy': {'nameKo': '버건디', 'nameEn': 'Burgundy', 'hex': '#7A2735'},
  'olive': {'nameKo': '올리브', 'nameEn': 'Olive', 'hex': '#6F7445'},
  'cream': {'nameKo': '크림', 'nameEn': 'Cream', 'hex': '#E9DEC6'},
  'charcoal': {'nameKo': '차콜', 'nameEn': 'Charcoal', 'hex': '#3F4043'},
  'camel': {'nameKo': '카멜', 'nameEn': 'Camel', 'hex': '#C1945F'},
  'cobalt': {'nameKo': '코발트', 'nameEn': 'Cobalt', 'hex': '#2648B0'},
};

const List<String> paintOrder = [
  'sage',
  'butter',
  'powder',
  'coral',
  'lilac',
  'terracotta',
  'burgundy',
  'olive',
  'cream',
  'charcoal',
  'camel',
  'cobalt',
];

void main() async {
  // Locate harness.json: check current dir or parent dir
  File harnessFile = File('harness.json');
  if (!harnessFile.existsSync()) {
    harnessFile = File('../harness.json');
  }
  if (!harnessFile.existsSync()) {
    stderr.writeln('Error: harness.json not found.');
    exit(1);
  }

  final content = await harnessFile.readAsString();
  final Map<String, dynamic> harness = jsonDecode(content);

  final designTokens = harness['designTokens'] as Map<String, dynamic>;
  final tokenScale = harness['tokenScale'] as Map<String, dynamic>;
  final motion = harness['motion'] as Map<String, dynamic>;
  final scaleColors = tokenScale['colors'] as Map<String, dynamic>;
  final durations = motion['durations'] as Map<String, dynamic>;

  final buffer = StringBuffer();
  buffer.writeln('// GENERATED CODE - DO NOT MODIFY BY HAND');
  buffer.writeln(
    '// Generated by `dart run tool/generate_tokens.dart` from harness.json.',
  );
  buffer.writeln('// Source of truth: harness.json (docs/design/README.md).');
  buffer.writeln('');
  buffer.writeln("import 'package:flutter/widgets.dart';");
  buffer.writeln('');

  // 1. Color Tokens
  buffer.writeln('/// Core color tokens from harness.json');
  buffer.writeln('abstract final class EselColors {');
  buffer.writeln(
    "  static const Color paper = Color(0xFFF9F9FB); // ${designTokens['paper']}",
  );
  buffer.writeln(
    "  static const Color ink = Color(0xFF292A27); // ${designTokens['ink']}",
  );
  buffer.writeln(
    "  static const Color muted = Color(0xFF71736C); // ${designTokens['muted']}",
  );
  buffer.writeln(
    "  static const Color hairline = Color(0xFFE0E1DC); // ${designTokens['hairline']}",
  );
  buffer.writeln(
    "  static const Color sub = Color(0xFF55574F); // ${scaleColors['sub']}",
  );
  buffer.writeln(
    "  static const Color line = Color(0xFFD8D9D3); // ${scaleColors['line']}",
  );
  buffer.writeln(
    "  static const Color photo = Color(0xFFEDEEEA); // ${scaleColors['photo']}",
  );
  buffer.writeln(
    "  static const Color error = Color(0xFFB3261E); // ${scaleColors['error']}",
  );
  buffer.writeln(
    "  static const Color dot = Color(0xFFAE8775); // ${scaleColors['dot']}",
  );
  buffer.writeln('}');
  buffer.writeln('');

  // 2. Glass Tokens
  buffer.writeln('/// Glass effect tokens');
  buffer.writeln('abstract final class EselGlassTokens {');
  buffer.writeln(
    '  static const Color background = Color(0x94F9F9FB); // rgba(249,249,251,0.58)',
  );
  buffer.writeln('  static const double blurSigma = 22.0;');
  buffer.writeln('  static const double saturate = 1.6;');
  buffer.writeln('  static const Color fallback = EselColors.paper;');
  buffer.writeln('}');
  buffer.writeln('');

  // 3. Spacing Tokens
  buffer.writeln('/// Spacing scale (4, 8, 12, 16, 20, 24, 32)');
  buffer.writeln('abstract final class EselSpacing {');
  final spacingList = (tokenScale['spacing'] as List<dynamic>).cast<int>();
  for (var i = 0; i < spacingList.length; i++) {
    buffer.writeln(
      '  static const double s${spacingList[i]} = ${spacingList[i]}.0;',
    );
  }
  buffer.writeln('  static const double gutter = 20.0;');
  buffer.writeln('  static const double touchMin = 48.0;');
  buffer.writeln('}');
  buffer.writeln('');

  // 4. Radius Tokens
  buffer.writeln('/// Border radius tokens');
  buffer.writeln('abstract final class EselRadius {');
  buffer.writeln('  static const double photo = 0.0;');
  buffer.writeln('  static const double spreadPhoto = 4.0;');
  buffer.writeln('  static const double card = 16.0;');
  buffer.writeln('  static const double colorPick = 22.0;');
  buffer.writeln('  static const double sheet = 28.0;');
  buffer.writeln('  static const double pill = 999.0;');
  buffer.writeln('}');
  buffer.writeln('');

  // 5. Size Tokens
  buffer.writeln('/// Dimensional sizes');
  buffer.writeln('abstract final class EselSizes {');
  buffer.writeln('  static const double screenWidth = 393.0;');
  buffer.writeln('  static const double screenHeight = 852.0;');
  buffer.writeln('  static const double touch = 48.0;');
  buffer.writeln('  static const double button = 54.0;');
  buffer.writeln('  static const double chip = 38.0;');
  buffer.writeln('  static const double segment = 36.0;');
  buffer.writeln('  static const double capsuleWidth = 196.0;');
  buffer.writeln('  static const double capsuleHeight = 60.0;');
  buffer.writeln('  static const double loginBar = 66.0;');
  buffer.writeln('  static const double gutter = 20.0;');
  buffer.writeln('  static const double innerPageText = 18.0;');
  buffer.writeln('}');
  buffer.writeln('');

  // 6. Motion Tokens
  buffer.writeln('/// Motion easing & durations');
  buffer.writeln('abstract final class EselMotion {');
  buffer.writeln('  static const Cubic easeOut = Cubic(0.23, 1.0, 0.32, 1.0);');
  buffer.writeln('  static const Cubic drawer = Cubic(0.32, 0.72, 0.0, 1.0);');
  buffer.writeln('  static const Cubic inOut = Cubic(0.77, 0.0, 0.175, 1.0);');
  buffer.writeln('');
  durations.forEach((key, val) {
    buffer.writeln(
      '  static const Duration $key = Duration(milliseconds: $val);',
    );
  });
  buffer.writeln('}');
  buffer.writeln('');

  // 7. Paint Enum & Definitions
  buffer.writeln('/// The 12 official point colors');
  buffer.writeln('enum EselPaint {');
  for (final key in paintOrder) {
    buffer.writeln('  $key,');
  }
  buffer.writeln('}');
  buffer.writeln('');

  buffer.writeln('class EselPaintInfo {');
  buffer.writeln('  final EselPaint paint;');
  buffer.writeln('  final String key;');
  buffer.writeln('  final String nameKo;');
  buffer.writeln('  final String nameEn;');
  buffer.writeln('  final Color color;');
  buffer.writeln('  final String hex;');
  buffer.writeln('  final String assetPath;');
  buffer.writeln('');
  buffer.writeln('  const EselPaintInfo({');
  buffer.writeln('    required this.paint,');
  buffer.writeln('    required this.key,');
  buffer.writeln('    required this.nameKo,');
  buffer.writeln('    required this.nameEn,');
  buffer.writeln('    required this.color,');
  buffer.writeln('    required this.hex,');
  buffer.writeln('    required this.assetPath,');
  buffer.writeln('  });');
  buffer.writeln('');
  buffer.writeln(
    '  /// Returns true if text on top of this color should be white',
  );
  buffer.writeln('  bool get isDark {');
  buffer.writeln('    return paint == EselPaint.burgundy ||');
  buffer.writeln('        paint == EselPaint.olive ||');
  buffer.writeln('        paint == EselPaint.charcoal ||');
  buffer.writeln('        paint == EselPaint.cobalt ||');
  buffer.writeln('        paint == EselPaint.terracotta;');
  buffer.writeln('  }');
  buffer.writeln('}');
  buffer.writeln('');

  buffer.writeln('abstract final class EselPaints {');
  buffer.writeln('  static const List<EselPaint> order = [');
  for (final key in paintOrder) {
    buffer.writeln('    EselPaint.$key,');
  }
  buffer.writeln('  ];');
  buffer.writeln('');
  buffer.writeln('  static const Map<EselPaint, EselPaintInfo> all = {');
  for (final key in paintOrder) {
    final meta = paintMeta[key]!;
    final hex = meta['hex']!;
    final hexInt = hex.replaceAll('#', '0xFF');
    buffer.writeln('    EselPaint.$key: EselPaintInfo(');
    buffer.writeln('      paint: EselPaint.$key,');
    buffer.writeln("      key: '$key',");
    buffer.writeln("      nameKo: '${meta['nameKo']}',");
    buffer.writeln("      nameEn: '${meta['nameEn']}',");
    buffer.writeln('      color: Color($hexInt),');
    buffer.writeln("      hex: '$hex',");
    buffer.writeln("      assetPath: 'assets/paint/esel-paint-$key.png',");
    buffer.writeln('    ),');
  }
  buffer.writeln('  };');
  buffer.writeln('');
  buffer.writeln('  static EselPaintInfo of(EselPaint paint) => all[paint]!;');
  buffer.writeln('  static EselPaintInfo? fromKey(String key) {');
  buffer.writeln('    for (final info in all.values) {');
  buffer.writeln('      if (info.key == key) return info;');
  buffer.writeln('    }');
  buffer.writeln('    return null;');
  buffer.writeln('  }');
  buffer.writeln('}');

  final outFile = File('lib/core/design/tokens.g.dart');
  outFile.parent.createSync(recursive: true);
  await outFile.writeAsString(buffer.toString());
  stdout.writeln('Successfully generated ${outFile.path}');
}
